export type TranslationDict = typeof translations.en;

interface I18nContextValue {
  lang: SupportedLanguage;
  setLang: (lang: SupportedLanguage) => void;
  t: TranslationDict;
}

const I18nContext = createContext<I18nContextValue | null>(null);

const LANG_STORAGE_KEY = 'levelup_rw_lang';

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<SupportedLanguage>(() => {
    try {
      const saved = window.localStorage.getItem(LANG_STORAGE_KEY);
      if (saved === 'rw' || saved === 'en' || saved === 'fr') return saved;
    } catch {
      // ignore storage errors
    }
    return 'en';
  });

  const setLang = (next: SupportedLanguage) => {
    setLangState(next);
    try {
      window.localStorage.setItem(LANG_STORAGE_KEY, next);
    } catch {
      // ignore
    }
  };

  return React.createElement(
    I18nContext.Provider,
    { value: { lang, setLang, t: translations[lang] as TranslationDict } },
    children,
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error('useI18n must be used inside I18nProvider');
  }
  return ctx;
}

export function pickLocalizedField(
  row: Record<string, any> | null | undefined,
  baseField: string,
  lang: SupportedLanguage,
): string {
  if (!row) return '';
  const suffixMap: Record<SupportedLanguage, string> = {
    en: '_en',
    rw: '_rw',
    fr: '_fr',
  };
  const camelSuffixMap: Record<SupportedLanguage, string> = {
    en: 'En',
    rw: 'Rw',
    fr: 'Fr',
  };

  const snakeKey = `${baseField}${suffixMap[lang]}`;
  const camelKey = `${baseField}${camelSuffixMap[lang]}`;
  return (
    row[snakeKey] ||
    row[camelKey] ||
    row[`${baseField}_en`] ||
    row[`${baseField}En`] ||
    row[baseField] ||
    ''
  );
}
